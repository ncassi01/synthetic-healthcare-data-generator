# Load data files
def load_json_data(file_path):
    """Load JSON data from a file."""
    try:
        with open(file_path, 'r') as f:
            return json.load(f)
    except Exception as e:
        app.logger.error(f"Error loading data from {file_path}: {e}")
        return None

