def get_statistics():
    """API endpoint to get statistics data."""
    stats = load_json_data(os.path.join(OUTPUT_DIR, 'statistics.json'))
    if stats is None:
        abort(500)
    
    # Get period parameter (monthly, quarterly, yearly)
    period = request.args.get('period', 'monthly')
    
    # Add additional statistics for the dashboard
    # 1. Claims by month/quarter/year
    claims = load_json_data(os.path.join(PROCESSED_DIR, 'claims.json'))
    if claims:
        # Process claims data to get distribution by time period
        claims_by_month = process_claims_by_time_period(claims, period)
        stats['claims_by_month'] = claims_by_month
        
        # Process claims data to get status distribution
        claim_status_counts = {}
        for claim in claims:
            status = claim.get('status', 'Unknown')
            claim_status_counts[status] = claim_status_counts.get(status, 0) + 1
        
        claim_status_distribution = [
            {'status': status, 'count': count}
            for status, count in claim_status_counts.items()
        ]
        stats['claim_status_distribution'] = claim_status_distribution
        
        # Process claims data to get top diagnoses
        diagnosis_counts = {}
        for claim in claims:
            diagnosis_codes = claim.get('diagnosis_codes', [])
            for code in diagnosis_codes:
                diagnosis_counts[code] = diagnosis_counts.get(code, 0) + 1
        
        # Sort by count and take top 10
        top_diagnoses = [
            {'code': code, 'count': count, 'description': get_diagnosis_description(code)}
            for code, count in sorted(diagnosis_counts.items(), key=lambda x: x[1], reverse=True)[:10]
        ]
        stats['top_diagnoses'] = top_diagnoses
    
    # 2. Authorization types
    authorizations = load_json_data(os.path.join(PROCESSED_DIR, 'authorizations.json'))
    if authorizations:
        auth_type_counts = {}
        for auth in authorizations:
            # Check for service_lines which contain service_type
            service_lines = auth.get('service_lines', [])
            if service_lines:
                for service_line in service_lines:
                    service_type = service_line.get('service_type', 'Unknown')
                    auth_type_counts[service_type] = auth_type_counts.get(service_type, 0) + 1
            else:
                # Fallback to top-level type if it exists
                auth_type = auth.get('type', 'Unknown')
                auth_type_counts[auth_type] = auth_type_counts.get(auth_type, 0) + 1
        
        authorization_types = [
            {'type': auth_type, 'count': count}
            for auth_type, count in auth_type_counts.items()
        ]
        stats['authorization_types'] = authorization_types
    
    # 3. Member age distribution
    members = load_json_data(os.path.join(PROCESSED_DIR, 'members.json'))
    if members:
        age_ranges = {
            '0-17': 0,
            '18-34': 0,
            '35-50': 0,
            '51-65': 0,
            '66+': 0
        }
        
        for member in members:
            age = member.get('age', 0)
            if age < 18:
                age_ranges['0-17'] += 1
            elif age < 35:
                age_ranges['18-34'] += 1
            elif age < 51:
                age_ranges['35-50'] += 1
            elif age < 66:
                age_ranges['51-65'] += 1
            else:
                age_ranges['66+'] += 1
        
        member_age_distribution = [
            {'range': age_range, 'count': count}
            for age_range, count in age_ranges.items()
        ]
        stats['member_age_distribution'] = member_age_distribution
    
    return jsonify(stats)

def process_claims_by_time_period(claims, period='monthly'):
    """Process claims data to get distribution by time period."""
    from datetime import datetime
    import calendar
    
    # Initialize result
    time_period_counts = {}
    
    for claim in claims:
        date_str = claim.get('date_received') or claim.get('submission_date')
        if not date_str:
            continue
        
        try:
            date = datetime.fromisoformat(date_str.replace('Z', '+00:00'))
            
            if period == 'monthly':
                # Format: "Jan 2025"
                period_key = date.strftime('%b %Y')
            elif period == 'quarterly':
                # Calculate quarter (1-4)
                quarter = (date.month - 1) // 3 + 1
                # Format: "Q1 2025"
                period_key = f"Q{quarter} {date.year}"
            elif period == 'yearly':
                # Format: "2025"
                period_key = str(date.year)
            else:
                # Default to monthly
                period_key = date.strftime('%b %Y')
            
            time_period_counts[period_key] = time_period_counts.get(period_key, 0) + 1
        except (ValueError, TypeError):
            # Skip invalid dates
            continue
    
    # Convert to sorted list of dictionaries
    result = []
    
