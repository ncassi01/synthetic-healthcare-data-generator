@app.route('/api/communications')
def get_communications():
    """API endpoint to get communication data."""
    comms = load_json_data(os.path.join(PROCESSED_DIR, 'communications.json'))
    if comms is None:
        abort(500)
    
    # Process communications to add sender and recipient fields
    processed_comms = []
    for comm in comms:
        # Create a processed copy of the communication
        processed_comm = comm.copy()
        
        # Ensure member_id is present (even if null)
        if 'member_id' not in processed_comm:
            processed_comm['member_id'] = None
        
        # Determine sender and recipient based on communication type and direction
        comm_type = comm.get('communication_type', '')
        
        if comm_type == 'pharmacy_communication':
            # Handle pharmacy communications
            if 'pharmacy_id' in comm:
                processed_comm['sender'] = f"pharmacy: {comm.get('pharmacy_id', 'Unknown')}"
            else:
                processed_comm['sender'] = comm.get('sender', 'Unknown')
                
            if 'provider_id' in comm:
                processed_comm['recipient'] = f"provider: {comm.get('provider_id', 'Unknown')}"
            else:
                processed_comm['recipient'] = comm.get('recipient', 'Unknown')
        elif comm_type == 'provider_to_provider':
            # Handle provider-to-provider communications
            if 'provider_id' in comm:
                processed_comm['sender'] = f"provider: {comm.get('provider_id', 'Unknown')}"
            else:
                processed_comm['sender'] = comm.get('sender', 'Unknown')
                
            if 'recipient_provider_id' in comm:
                processed_comm['recipient'] = f"provider: {comm.get('recipient_provider_id', 'Unknown')}"
            else:
                processed_comm['recipient'] = comm.get('recipient', 'Unknown')
        elif comm_type == 'care_team_discussion':
            # Handle care team discussions
            if 'provider_id' in comm:
                processed_comm['sender'] = f"provider: {comm.get('provider_id', 'Unknown')}"
            else:
                processed_comm['sender'] = comm.get('sender', 'Unknown')
                
            if 'recipient_provider_id' in comm:
                processed_comm['recipient'] = f"provider: {comm.get('recipient_provider_id', 'Unknown')}"
            else:
                processed_comm['recipient'] = comm.get('recipient', 'Unknown')
        elif comm.get('direction') == 'provider_to_member':
            processed_comm['sender'] = comm.get('provider_id', 'Provider')
            processed_comm['recipient'] = comm.get('member_id', 'Member')
        elif comm.get('direction') == 'member_to_provider':
            processed_comm['sender'] = comm.get('member_id', 'Member')
            processed_comm['recipient'] = comm.get('provider_id', 'Provider')
        else:
            processed_comm['sender'] = comm.get('sender', 'Unknown')
            processed_comm['recipient'] = comm.get('recipient', 'Unknown')
        
        processed_comms.append(processed_comm)
    
    return jsonify(processed_comms)

